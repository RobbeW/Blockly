/* Pack local fonts and canvas images for file:// previews as well as hosted exams. */
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const files=[
  'assessment/vendor/fonts/NotoSans-Regular.ttf','assessment/vendor/fonts/NotoSans-Bold.ttf','assessment/vendor/fonts/NotoSansMono-Regular.ttf',
  'assessment/assets/program.png',...Array.from({length:4},(_,i)=>`assessment/assets/maze-${i+1}.png`),
  'assessment/assets/infinite-loop-a.png',
  ...['a','b','c'].map(version=>`assessment/assets/loop-boundary-${version}.png`),
  ...['b','c'].flatMap(version=>[`assessment/assets/program-${version}.png`,...Array.from({length:4},(_,i)=>`assessment/assets/maze-${version}-${i+1}.png`)]),
  'assets/tiles_pegman.png','assets/pegman.png','assets/marker.png'
];
const assets=Object.fromEntries(files.map(file=>[file,`data:${file.endsWith('.ttf')?'font/ttf':'image/png'};base64,${fs.readFileSync(path.join(root,file)).toString('base64')}`]));
fs.writeFileSync(path.join(root,'assessment/assets-bundle.js'),'/* Generated by scripts/build-assessment-assets.cjs. Original asset/font licenses apply. */\nwindow.ASSESSMENT_ASSETS = '+JSON.stringify(assets)+';\n');
console.log(`Bundled ${files.length} fonts/images for direct-file and hosted use.`);
